require('dotenv/config')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const jwt = require('jsonwebtoken')
const { PrismaClient } = require('@prisma/client')
const prisma = new PrismaClient()
const database = new URL(process.env.DATABASE_URL)
assert(['localhost', '127.0.0.1'].includes(database.hostname) && database.port === '5435', 'Local test database on port 5435 required')
const tag = randomUUID()
const users = []
const reportIds = []
async function user(label, role = 'USER') {
  const row = await prisma.user.create({ data: { name: `PRIVATE_ACCOUNT_${label}`, email: `${tag}-${label}@example.test`, passwordHash: '!test-only', role, communityProfile: { create: { displayName: `Chat check ${label} ${tag}` } } } })
  users.push(row.id)
  return { id: row.id, token: jwt.sign({ email: row.email, name: row.name, role }, process.env.JWT_SECRET, { subject: row.id, expiresIn: '20m' }) }
}
async function call(path, actor, method = 'GET', body) {
  const response = await fetch(`http://localhost:4000/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(actor ? { Authorization: `Bearer ${actor.token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) })
  const data = await response.json()
  return { status: response.status, data, retry: response.headers.get('retry-after') }
}
const base = '/community/conversations'
async function invite(from, to, postId) {
  return call(base, from, 'POST', { recipientId: to.id, postId, content: 'Hello from the integration check', clientRequestId: randomUUID() })
}
async function send(id, from, clientRequestId = randomUUID()) {
  return call(`${base}/${id}/messages`, from, 'POST', { content: 'Private test message', clientRequestId })
}
async function main() {
  const [a,b,c,admin,d] = await Promise.all([user('a'), user('b'), user('c'), user('admin','ADMIN'), user('d')])
  const post = await prisma.communityPost.create({ data: { userId: b.id, title: 'Integration source', content: 'Test source post', isAnonymous: true } })
  assert.equal((await invite(a,b,post.id)).status,404)
  await prisma.communityPost.update({ where: { id: post.id }, data: { isAnonymous: false, hiddenAt: new Date() } })
  assert.equal((await invite(a,b,post.id)).status,404)
  await prisma.communityPost.update({ where: { id: post.id }, data: { hiddenAt: null } })
  assert.equal((await call(base,null)).status,401)
  assert.equal((await call(base,admin)).status,403)
  assert.equal((await invite(a,a)).status,400)
  const [first, second] = await Promise.all([invite(a,b,post.id), invite(a,b,post.id)])
  assert.equal(first.status,201); assert.equal(second.status,201)
  const id=first.data.conversationId
  assert.equal(id,second.data.conversationId)
  assert.equal(await prisma.communityDirectMessage.count({ where:{conversationId:id} }),1)
  assert.equal((await send(id,a)).status,409)
  assert.equal((await call(base,a,'POST',{recipientId:b.id,content:'x'.repeat(501),clientRequestId:randomUUID()})).status,400)
  assert.equal((await call(`${base}/${id}/messages`,a,'POST',{content:'x'.repeat(2001),clientRequestId:randomUUID()})).status,400)
  assert.equal((await call(`${base}/${id}/messages`,c)).status,404)
  assert.equal((await call(`${base}/${id}/action`,a,'POST',{action:'ACCEPT'})).status,403)
  assert.equal((await call(`${base}/${id}/action`,b,'POST',{action:'ACCEPT'})).status,200)
  const requestId=randomUUID()
  const duplicates=await Promise.all([send(id,a,requestId),send(id,a,requestId)])
  assert.equal(duplicates[0].status,201); assert.equal(duplicates[1].status,201)
  assert.equal(duplicates[0].data.message.id,duplicates[1].data.message.id)
  const received=duplicates[0].data.message
  const unread=await call(`${base}/unread`,b)
  assert.equal(unread.data.unread,2)
  assert.equal((await call(`${base}/${id}/read`,b,'PATCH',{messageId:received.id})).status,200)
  assert.equal((await call(`${base}/unread`,b)).data.unread,0)
  const newer=await send(id,a)
  await call(`${base}/${id}/read`,b,'PATCH',{messageId:received.id})
  assert.equal((await call(`${base}/unread`,b)).data.unread,1)
  const beforeBlock=await call(`${base}/${id}`,b)
  assert(!JSON.stringify(beforeBlock.data).includes('PRIVATE_ACCOUNT'))
  assert(!JSON.stringify(beforeBlock.data).includes('@example.test'))
  const report=await call(`${base}/${id}/messages/${received.id}/report`,b,'POST',{reason:'HARASSMENT',details:'Integration test'})
  assert.equal(report.status,201); reportIds.push(report.data.reportId)
  assert.equal((await call(`${base}/${id}/messages/${received.id}/report`,b,'POST',{reason:'HARASSMENT'})).status,409)
  assert.equal((await call(`${base}/${id}/messages/${received.id}/report`,a,'POST',{reason:'HARASSMENT'})).status,404)
  assert.equal((await call('/admin/community/reports',b)).status,403)
  const queue=await call('/admin/community/reports',admin)
  const entry=queue.data.reports.find((row)=>row.id===report.data.reportId)
  assert(entry)
  assert.equal(entry.contentSnapshot,received.content)
  assert.deepEqual(Object.keys(entry.directMessage).sort(),['hiddenAt','id'])
  assert.equal((await call(`${base}/${id}/messages`,admin)).status,403)
  assert.equal((await call(`/admin/community/reports/${entry.id}/action`,admin,'POST',{action:'HIDE',reason:'Integration hide'})).status,200)
  const hidden=(await call(`${base}/${id}/messages`,b)).data.messages.find((row)=>row.id===received.id)
  assert.equal(hidden.content,null); assert.equal(hidden.hidden,true)
  await call(`/admin/community/reports/${entry.id}/action`,admin,'POST',{action:'RESTORE',reason:'Integration restore'})
  assert.equal((await call(`${base}/${id}/messages`,b)).data.messages.find((row)=>row.id===received.id).content,received.content)
  await call(`/community/members/${a.id}/block`,b,'POST')
  assert.equal((await call(`${base}/${id}`,b)).data.conversation.blockedByMe,true)
  assert.equal((await call(`${base}/${id}`,a)).data.conversation.blockedByMe,false)
  assert.equal((await send(id,a)).status,403); assert.equal((await send(id,b)).status,403)
  assert.equal((await call(`${base}/${id}/messages`,b)).status,200)
  assert((await call('/community/blocks',b)).data.members.some((member)=>member.id===a.id))
  await call(`/community/members/${b.id}/block`,a,'POST')
  await call(`/community/members/${a.id}/block`,b,'DELETE')
  assert.equal((await call(`${base}/${id}`,b)).data.conversation.blockedByMe,false)
  assert.equal((await send(id,b)).status,403)
  assert.equal((await call(`${base}/${id}`,a)).data.conversation.blockedByMe,true)
  await call(`/community/members/${b.id}/block`,a,'DELETE')
  assert.equal((await send(id,a)).status,201)
  await call(`/admin/community/reports/${entry.id}/action`,admin,'POST',{action:'SUSPEND_AUTHOR',reason:'Integration suspension'})
  assert.equal((await send(id,a)).status,403); assert.equal((await send(id,b)).status,403)
  await call(`/admin/community/reports/${entry.id}/action`,admin,'POST',{action:'UNSUSPEND_AUTHOR',reason:'Integration restore user'})
  assert.equal((await send(id,a)).status,201)
  const ab=await invite(c,d)
  assert.equal(ab.status,201)
  await call(`${base}/${ab.data.conversationId}/action`,d,'POST',{action:'DECLINE'})
  assert.equal((await invite(c,d)).status,409)
  assert.equal((await invite(d,c)).status,201)
  await call(`${base}/${ab.data.conversationId}/action`,d,'POST',{action:'CANCEL'})
  assert.equal((await invite(d,c)).status,409)
  const re=await invite(c,d)
  assert.equal(re.status,201)
  await call(`/community/members/${c.id}/block`,d,'POST')
  assert.equal((await call(`${base}/${re.data.conversationId}`,c)).data.conversation.status,'CANCELLED')
  assert.equal((await call(`${base}/${re.data.conversationId}/action`,d,'POST',{action:'ACCEPT'})).status,403)
  const old = new Date(Date.now()-120000)
  await prisma.communityDirectMessage.updateMany({where:{senderId:a.id},data:{createdAt:old}})
  await prisma.communityDirectMessage.createMany({data:Array.from({length:35},()=>({conversationId:id,senderId:a.id,clientRequestId:randomUUID(),content:'History page',createdAt:old}))})
  const latest=await call(`${base}/${id}/messages`,b)
  assert.equal(latest.data.messages.length,30); assert(latest.data.nextCursor)
  const older=await call(`${base}/${id}/messages?before=${latest.data.nextCursor}`,b)
  assert(older.data.messages.every((row)=>row.seq<latest.data.nextCursor))
  const catchup=await call(`${base}/${id}/messages?after=${received.seq}`,b)
  assert.equal(catchup.data.messages.length,30); assert(catchup.data.nextAfter)
  assert(catchup.data.messages.every((row)=>row.seq>received.seq))
  assert((await call(`${base}/${id}/messages?after=${catchup.data.nextAfter}`,b)).data.messages.length>0)
  const newerSeq=newer.data.message.seq
  assert(latest.data.messages.every((row)=>row.seq>newerSeq))
  for(let i=0;i<20;i++) assert.equal((await send(id,a)).status,201)
  const limited=await send(id,a)
  assert.equal(limited.status,429); assert(Number(limited.retry)>0)
  await prisma.communityNotification.createMany({data:Array.from({length:10},()=>({userId:b.id,actorId:a.id,type:'CHAT_INVITATION'}))})
  assert.equal((await invite(a,c)).status,429)
  await prisma.communityPost.delete({where:{id:post.id}})
  assert.equal((await call(`${base}/${id}`,b)).data.conversation.sourcePost,null)
  assert.equal((await call(`${base}/${id}/messages`,b)).status,200)
  await prisma.doctorProfile.create({data:{userId:d.id,displayName:'Chat check doctor',title:'BS.',specialty:'Test',workplace:'Test',city:'Test',bio:'Test',languages:[]}})
  assert.equal((await call(base,d)).status,403)
  assert.equal((await invite(b,d)).status,403)
  console.log('PASS: invitations, consent, anonymity, duplicate/concurrent send, unread, cursor pagination, ownership, reports, admin privacy, hide/restore, blocks, suspension, limits and deleted source')
}
main().catch((error)=>{ console.error(error); process.exitCode=1 }).finally(async()=>{
  if(reportIds.length) await prisma.communityModerationAction.deleteMany({where:{reportId:{in:reportIds}}})
  await prisma.user.deleteMany({where:{id:{in:users}}})
  await prisma.$disconnect()
})
