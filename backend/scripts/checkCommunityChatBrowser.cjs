// Optional browser check: playwright-core is installed in TEMP, outside project dependencies.
require('dotenv/config')
const assert = require('node:assert/strict')
const path = require('node:path')
const { randomUUID } = require('node:crypto')
const jwt = require('jsonwebtoken')
const { PrismaClient } = require('@prisma/client')
const { chromium } = require(path.join(process.env.TEMP, 'aimbrace-chat-browser-check/node_modules/playwright-core'))
const prisma = new PrismaClient()
const database = new URL(process.env.DATABASE_URL)
assert(['localhost','127.0.0.1'].includes(database.hostname) && database.port === '5435')
const users = []
let browser
async function makeUser(label) {
  const row = await prisma.user.create({ data: { name: `Private browser ${label}`, email: `${randomUUID()}@example.test`, passwordHash: '!browser-only', communityProfile: { create: { displayName: `Browser parent ${label}` } } } })
  users.push(row.id)
  return { id: row.id, displayName: `Browser parent ${label}`, token: jwt.sign({ name: row.name, email: row.email, role: 'USER' }, process.env.JWT_SECRET, { subject: row.id, expiresIn:'15m' }) }
}
async function main() {
  const a=await makeUser(randomUUID().slice(0,6)), b=await makeUser(randomUUID().slice(0,6)), c=await makeUser(randomUUID().slice(0,6))
  const post=await prisma.communityPost.create({data:{userId:b.id,title:'Browser chat source',content:'Integration browser source content'}})
  const anon=await prisma.communityPost.create({data:{userId:b.id,title:'Anonymous browser source',content:'Anonymous integration browser source',isAnonymous:true}})
  const root=await prisma.communityComment.create({data:{userId:c.id,postId:post.id,content:'Comment avatar browser check'}})
  await prisma.communityComment.create({data:{userId:c.id,postId:post.id,parentId:root.id,content:'Reply avatar browser check'}})
  await prisma.communityComment.create({data:{userId:a.id,postId:post.id,content:'Own avatar browser check'}})
  await prisma.communityComment.create({data:{userId:c.id,postId:post.id,isAnonymous:true,content:'Anonymous avatar browser check'}})
  console.log('Launching browser')
  browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,timeout:20000})
  const errors=[]
  async function page(actor) {
    const context=await browser.newContext({viewport:{width:1440,height:1000}})
    await context.addInitScript((token)=>localStorage.setItem('asdr_token',token),actor.token)
    const page=await context.newPage()
    page.setDefaultTimeout(15000)
    page.setDefaultNavigationTimeout(15000)
    page.on('pageerror',(error)=>errors.push(error.message))
    return page
  }
  const pa=await page(a), pb=await page(b)
  console.log('Opening community post')
  await pa.goto(`http://localhost:5173/community/post/${post.id}`)
  const commentCard=pa.getByText('Comment avatar browser check',{exact:true}).locator('..')
  await commentCard.getByRole('button',{name:`Nhắn riêng với ${c.displayName}`,exact:true}).first().click()
  await pa.getByRole('dialog').getByRole('heading',{name:`Gửi lời mời cho ${c.displayName}`,exact:true}).waitFor()
  await pa.getByRole('dialog').getByRole('button',{name:'Hủy',exact:true}).click()
  const replyCard=pa.getByText('Reply avatar browser check',{exact:true}).locator('..')
  await replyCard.getByRole('button',{name:`Nhắn riêng với ${c.displayName}`,exact:true}).click()
  await pa.getByRole('dialog').getByRole('heading',{name:`Gửi lời mời cho ${c.displayName}`,exact:true}).waitFor()
  await pa.getByRole('dialog').getByRole('button',{name:'Hủy',exact:true}).click()
  assert.equal(await pa.getByText('Own avatar browser check',{exact:true}).locator('..').getByRole('button',{name:/Nhắn riêng với/}).count(),0)
  assert.equal(await pa.getByText('Anonymous avatar browser check',{exact:true}).locator('..').getByRole('button',{name:/Nhắn riêng với/}).count(),0)
  await pa.getByRole('button',{name:`Nhắn riêng với ${b.displayName}`,exact:true}).click()
  const invitation=pa.getByRole('dialog')
  await invitation.getByRole('textbox').fill('Hello from browser invitation')
  await invitation.getByRole('button',{name:'Gửi lời mời',exact:true}).click()
  await pa.waitForURL('**/community/messages/*')
  console.log('Invitation sent')
  const conversationId=pa.url().split('/').at(-1)
  await pa.getByText('Chờ người nhận chấp nhận lời mời.',{exact:true}).waitFor()
  await pb.goto(`http://localhost:5173/community/messages/${conversationId}`)
  await pb.getByRole('button',{name:'Chấp nhận',exact:true}).click()
  console.log('Invitation accepted')
  await pa.getByRole('textbox',{name:'Tin nhắn',exact:true}).waitFor()
  await pa.getByRole('textbox',{name:'Tin nhắn',exact:true}).fill('Message sent with Enter')
  await pa.getByRole('textbox',{name:'Tin nhắn',exact:true}).press('Enter')
  await pb.getByText('Message sent with Enter',{exact:true}).waitFor()
  await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).fill('First line')
  await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).press('Shift+Enter')
  await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).press('End')
  await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).type('Second line')
  assert((await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).inputValue()).includes('\n'))
  await pb.getByRole('button',{name:'Gửi',exact:true}).click()
  await pa.getByText('First line\nSecond line',{exact:true}).waitFor()
  await pa.screenshot({path:path.join(process.env.TEMP,'aimbrace-chat-desktop.png'),fullPage:true})
  await pb.getByRole('button',{name:'Báo cáo',exact:true}).last().click()
  const report=pb.getByRole('dialog')
  await report.getByText('Quản trị viên sẽ nhận bản sao tin nhắn này và lý do bạn báo cáo.').waitFor()
  await report.getByRole('button',{name:'Gửi báo cáo',exact:true}).click()
  await report.waitFor({state:'hidden'})
  await pb.setViewportSize({width:390,height:844})
  assert(await pb.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No horizontal overflow on mobile')
  await pb.screenshot({path:path.join(process.env.TEMP,'aimbrace-chat-mobile.png'),fullPage:true})
  await pb.getByRole('button',{name:'Chặn',exact:true}).click()
  await pb.getByRole('dialog').getByRole('heading',{name:`Chặn ${a.displayName}?`,exact:true}).waitFor()
  await pb.screenshot({path:path.join(process.env.TEMP,'aimbrace-block-confirm-mobile.png'),fullPage:true})
  await pb.getByRole('dialog').getByRole('button',{name:'Hủy',exact:true}).click()
  await pb.getByRole('textbox',{name:'Tin nhắn',exact:true}).waitFor()
  await pb.getByRole('button',{name:'Chặn',exact:true}).click()
  await pb.getByRole('dialog').getByRole('button',{name:'Chặn thành viên',exact:true}).click()
  await pa.getByText('Hiện không thể gửi tin trong cuộc trò chuyện này.',{exact:true}).waitFor()
  await pb.getByRole('button',{name:'Bỏ chặn',exact:true}).waitFor()
  await pb.getByRole('button',{name:'Bỏ chặn',exact:true}).click()
  await pb.getByRole('dialog').getByRole('button',{name:'Bỏ chặn',exact:true}).click()
  await pa.getByRole('textbox',{name:'Tin nhắn',exact:true}).waitFor()
  await pb.getByRole('button',{name:'Chặn',exact:true}).click()
  await pb.getByRole('dialog').getByRole('button',{name:'Chặn thành viên',exact:true}).click()
  await pb.getByRole('button',{name:'Bỏ chặn',exact:true}).waitFor()
  await pb.getByRole('button',{name:'← Hộp thư',exact:true}).click()
  await pb.getByRole('button',{name:'Trò chuyện',exact:true}).waitFor()
  await pb.getByRole('button',{name:/Tài khoản đã chặn/}).click()
  await pb.getByRole('button',{name:'Bỏ chặn',exact:true}).click()
  await pb.getByRole('dialog').getByRole('button',{name:'Bỏ chặn',exact:true}).click()
  await pb.getByText('Bạn chưa chặn thành viên nào.',{exact:true}).waitFor()
  await pb.getByText(`Đã bỏ chặn ${a.displayName}.`,{exact:true}).waitFor()
  await pa.goto(`http://localhost:5173/community/post/${anon.id}`)
  await pa.getByText('Anonymous browser source',{exact:true}).waitFor()
  assert.equal(await pa.getByRole('button',{name:'Nhắn riêng',exact:true}).count(),0)
  assert.equal(await pa.getByRole('button',{name:/Nhắn riêng với/}).count(),0)
  assert.deepEqual(errors,[])
  console.log('PASS browser: invitation, accept, Enter/Shift+Enter, live messages, report dialog, block, anonymous post, desktop/mobile navigation, no overflow or page errors')
  console.log('Screenshots: '+path.join(process.env.TEMP,'aimbrace-chat-desktop.png')+' ; '+path.join(process.env.TEMP,'aimbrace-chat-mobile.png'))
}
main().catch((error)=>{console.error(error);process.exitCode=1}).finally(async()=>{
  if(browser) await browser.close()
  await prisma.user.deleteMany({where:{id:{in:users}}})
  await prisma.$disconnect()
})
